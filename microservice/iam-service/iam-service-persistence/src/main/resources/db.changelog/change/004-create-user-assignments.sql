CREATE TABLE user_roles (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            user_id BIGINT NOT NULL REFERENCES users(id),
                            role_id BIGINT NOT NULL REFERENCES roles(id),
                            assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            assigned_by VARCHAR(100) NOT NULL,
                            expires_at TIMESTAMPTZ,
                            revoked_at TIMESTAMPTZ,
                            revoked_by VARCHAR(100),
                            reason VARCHAR(255),
                            version BIGINT NOT NULL DEFAULT 0,
                            CONSTRAINT ck_user_role_expiry
                                CHECK (expires_at IS NULL OR expires_at > assigned_at),
                            CONSTRAINT ck_user_role_revocation CHECK (
                                (revoked_at IS NULL AND revoked_by IS NULL)
                                    OR (revoked_at IS NOT NULL AND revoked_by IS NOT NULL
                                    AND revoked_at >= assigned_at)
                                )
);

CREATE TABLE user_permissions (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  user_id BIGINT NOT NULL REFERENCES users(id),
                                  permission_id BIGINT NOT NULL REFERENCES permissions(id),
                                  effect VARCHAR(5) NOT NULL,
                                  assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  assigned_by VARCHAR(100) NOT NULL,
                                  expires_at TIMESTAMPTZ,
                                  revoked_at TIMESTAMPTZ,
                                  revoked_by VARCHAR(100),
                                  reason VARCHAR(255),
                                  version BIGINT NOT NULL DEFAULT 0,
                                  CONSTRAINT ck_user_permission_effect
                                      CHECK (effect IN ('GRANT', 'DENY')),
                                  CONSTRAINT ck_user_permission_expiry
                                      CHECK (expires_at IS NULL OR expires_at > assigned_at),
                                  CONSTRAINT ck_user_permission_revocation CHECK (
                                      (revoked_at IS NULL AND revoked_by IS NULL)
                                          OR (revoked_at IS NOT NULL AND revoked_by IS NOT NULL
                                          AND revoked_at >= assigned_at)
                                      )
);

CREATE INDEX idx_user_roles_user_id ON user_roles(user_id);
CREATE INDEX idx_user_roles_role_id ON user_roles(role_id);
CREATE INDEX idx_user_permissions_user_id ON user_permissions(user_id);
CREATE INDEX idx_user_permissions_permission_id
    ON user_permissions(permission_id);
